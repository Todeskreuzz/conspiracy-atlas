#!/usr/bin/env node
// Generates an additive content migration from a case-file batch in data/ (same shapes as data/seed.mjs).
// Unlike 0002_seed.sql it uses no fixed ids: every reference is resolved by slug (or source title), so the
// migration applies cleanly to a database that already holds community content and admin edits.
// Usage: node scripts/generate-addition.mjs data/cases-2.mjs migrations/d1/0005_more_cases.sql
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import * as seed from '../data/seed.mjs';
import { sqlLiteral as q } from '../shared/backup-core.mjs';

const [inFile, outFile] = process.argv.slice(2);
if (!inFile || !outFile) {
  console.error('Usage: node scripts/generate-addition.mjs <batch.mjs> <out.sql>');
  process.exit(1);
}
const batch = await import(pathToFileURL(resolve(inFile)).href);
const list = (name) => batch[name] ?? [];

const out = [];
const emit = (s) => out.push(s);
const slugify = (s) =>
  s
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

// Every key must exist either in the base seed or in this batch.
const known = {
  location: [...seed.locations, ...list('locations')],
  organization: [...seed.organizations, ...list('organizations')],
  person: [...seed.people, ...list('people')],
  event: [...seed.events, ...list('events')],
  document: [...seed.documents, ...list('documents')],
  theory: [...seed.theories, ...list('theories')],
  source: [...seed.sources, ...list('sources')],
};
const lookup = Object.fromEntries(Object.entries(known).map(([type, items]) => [type, new Map(items.map((i) => [i.key, i]))]));
const item = (type, key) => {
  const found = lookup[type].get(key);
  if (!found) throw new Error(`Unknown ${type} key: ${key}`);
  return found;
};
const TABLE = { location: 'locations', organization: 'organizations', person: 'people', event: 'events', document: 'documents', theory: 'theories' };
const idOf = (type, key) => {
  if (type === 'source') {
    const s = item('source', key);
    return `(SELECT id FROM sources WHERE title = ${q(s.title)} AND publisher = ${q(s.publisher)} ORDER BY id LIMIT 1)`;
  }
  // Locations, organizations, people, events and documents use the key as slug; theories have their own slug.
  const slug = type === 'theory' ? item('theory', key).slug : (item(type, key), key);
  return `(SELECT id FROM ${TABLE[type]} WHERE slug = ${q(slug)})`;
};
const catId = (slug) => `(SELECT id FROM categories WHERE slug = ${q(slug)})`;
const translation = (type, idSql, field, value) =>
  emit(`INSERT OR REPLACE INTO translations (entity_type, entity_id, locale, field, value) VALUES (${q(type)}, ${idSql}, 'de', ${q(field)}, ${q(value)});`);

emit(`-- Additional case files. Generated by scripts/generate-addition.mjs from ${inFile} – do not edit by hand.`);
emit('-- References are resolved by slug, so this applies on top of an existing archive.');

for (const l of list('locations')) {
  emit(
    `INSERT INTO locations (slug, name, country_code, lat, lng, region_kind, description) VALUES (${q(l.key)}, ${q(l.name)}, ${q(l.country)}, ${l.lat}, ${l.lng}, ${q(l.kind)}, ${q(l.description)});`,
  );
}
for (const o of list('organizations')) {
  emit(
    `INSERT INTO organizations (slug, name, kind, description, founded, country, location_id) VALUES (${q(o.key)}, ${q(o.name)}, ${q(o.kind)}, ${q(o.description)}, ${q(o.founded)}, ${q(o.country)}, ${o.location ? idOf('location', o.location) : 'NULL'});`,
  );
}
for (const p of list('people')) {
  emit(`INSERT INTO people (slug, name, role, description, born, died) VALUES (${q(p.key)}, ${q(p.name)}, ${q(p.role)}, ${q(p.description)}, ${q(p.born)}, ${q(p.died)});`);
}
for (const s of list('sources')) {
  emit(
    `INSERT INTO sources (title, publisher, author, published_date, source_type, is_primary, url, last_checked, quality_note, notes) VALUES (${q(s.title)}, ${q(s.publisher)}, ${q(s.author)}, ${q(s.date)}, ${q(s.type)}, ${s.primary ? 1 : 0}, ${q(s.url)}, NULL, ${q(s.quality)}, ${q(s.url ? 'URL pending manual verification.' : 'Print/offline source; no URL.')});`,
  );
}

for (const t of list('theories')) {
  const tid = idOf('theory', t.key);
  const body = {
    type: 'doc',
    content: [t.background, t.origin].filter(Boolean).map((p) => ({ type: 'paragraph', content: [{ type: 'text', text: p }] })),
  };
  emit(
    `INSERT INTO theories (slug, title, subtitle, summary, background, origin_story, body_json, category_id, evidence_status, image_path, image_credit, origin, is_published) VALUES (${q(t.slug)}, ${q(t.title)}, ${q(t.subtitle)}, ${q(t.summary)}, ${q(t.background)}, ${q(t.origin)}, ${q(JSON.stringify(body))}, ${catId(t.category)}, ${q(t.status)}, ${q(t.image ?? null)}, ${q(t.image ? t.imageCredit : null)}, 'editorial', 1);`,
  );
  for (const tag of t.tags) {
    const slug = slugify(tag);
    emit(`INSERT OR IGNORE INTO tags (slug, name) VALUES (${q(slug)}, ${q(tag)});`);
    emit(`INSERT OR IGNORE INTO theory_tags (theory_id, tag_id) VALUES (${tid}, (SELECT id FROM tags WHERE slug = ${q(slug)}));`);
  }
  let counterIndex = 0;
  t.claims.forEach(([text, status, sourceKeys, counter, counterSources], ci) => {
    emit(`INSERT INTO claims (theory_id, text, evidence_status, position) VALUES (${tid}, ${q(text)}, ${q(status)}, ${ci});`);
    const cid = `(SELECT id FROM claims WHERE theory_id = ${tid} AND position = ${ci})`;
    for (const sk of sourceKeys) {
      // Origin publications of a claim are recorded as "context", never as proof.
      const relation = status === 'historically_documented' || status === 'supported_by_evidence' ? 'documents' : 'context';
      emit(`INSERT INTO evidence (source_id, theory_id, claim_id, relation) VALUES (${idOf('source', sk)}, ${tid}, ${cid}, ${q(relation)});`);
    }
    if (counter) {
      emit(`INSERT INTO counter_arguments (theory_id, claim_id, text, position) VALUES (${tid}, ${cid}, ${q(counter)}, ${counterIndex});`);
      const caid = `(SELECT id FROM counter_arguments WHERE claim_id = ${cid})`;
      for (const sk of counterSources ?? []) {
        emit(`INSERT INTO evidence (source_id, theory_id, counter_argument_id, relation) VALUES (${idOf('source', sk)}, ${tid}, ${caid}, 'refutes');`);
      }
      if (t.de?.counters?.[counterIndex]) translation('counter_argument', caid, 'text', t.de.counters[counterIndex]);
      counterIndex++;
    }
    if (t.de?.claims?.[ci]) translation('claim', cid, 'text', t.de.claims[ci]);
  });
  for (const [sk, relation, note] of t.general ?? []) {
    emit(`INSERT INTO evidence (source_id, theory_id, relation, note) VALUES (${idOf('source', sk)}, ${tid}, ${q(relation)}, ${q(note)});`);
  }
  for (const f of ['title', 'subtitle', 'summary', 'background']) if (t.de?.[f]) translation('theory', tid, f, t.de[f]);
}

for (const e of list('events')) {
  emit(
    `INSERT INTO events (slug, title, description, start_date, end_date, start_year, end_year, is_period, location_id, category_id, evidence_status) VALUES (${q(e.key)}, ${q(e.title)}, ${q(e.description)}, ${q(e.start)}, ${q(e.end ?? null)}, ${e.year}, ${e.endYear ?? 'NULL'}, ${e.period ? 1 : 0}, ${e.location ? idOf('location', e.location) : 'NULL'}, ${catId(e.category)}, ${q(e.status)});`,
  );
  if (e.de) {
    translation('event', idOf('event', e.key), 'title', e.de[0]);
    translation('event', idOf('event', e.key), 'description', e.de[1]);
  }
}

for (const d of list('documents')) {
  const src = item('source', d.source);
  emit(
    `INSERT INTO documents (slug, title, description, document_type, url, source_id, published_date, archive_name, license_note) VALUES (${q(d.key)}, ${q(d.title)}, ${q(src.quality)}, ${q(d.type)}, ${q(src.url)}, ${idOf('source', d.source)}, ${q(src.date)}, ${q(d.archive)}, ${q(d.license)});`,
  );
}

const relId = ([ft, fk, tt, tk, kind]) =>
  `(SELECT id FROM relationships WHERE from_type = ${q(ft)} AND from_id = ${idOf(ft, fk)} AND to_type = ${q(tt)} AND to_id = ${idOf(tt, tk)} AND kind = ${q(kind)})`;
for (const r of list('relationships')) {
  const [ft, fk, tt, tk, kind, verification, label] = r;
  emit(
    `INSERT OR IGNORE INTO relationships (from_type, from_id, to_type, to_id, kind, verification, label) VALUES (${q(ft)}, ${idOf(ft, fk)}, ${q(tt)}, ${idOf(tt, tk)}, ${q(kind)}, ${q(verification)}, ${q(label)});`,
  );
}

// Investigation wall --------------------------------------------------------------------------
// Cards that the base seed already put on the wall keep their place; new cards go below the existing grid.
const onWall = new Set(seed.theories.map((t) => `theory:${t.key}`));
for (const [ft, , tt, tk] of seed.relationships) if (ft === 'theory' && tt !== 'theory') onWall.add(`${tt}:${tk}`);

function nodeFor(type, key) {
  const it = item(type, key);
  switch (type) {
    case 'theory':
      return { kind: 'theory', title: it.title, summary: it.summary, category: it.category, status: it.status, image: it.image ?? '/media/cards/theory.svg', tags: it.tags, group: it.category };
    case 'event':
      return { kind: 'event', title: it.title, summary: `${it.start}${it.end ? ` – ${it.end}` : ''}: ${it.description}`, category: it.category, status: it.status, image: '/media/cards/event.svg', tags: [String(it.year)], group: 'event' };
    case 'organization':
      return { kind: ['agency', 'commission', 'institution'].includes(it.kind) ? 'institution' : 'organization', title: it.name, summary: it.description, category: null, status: null, image: '/media/cards/organization.svg', tags: [it.country], group: 'organization' };
    case 'person':
      return { kind: 'person', title: it.name, summary: `${it.role}. ${it.description}`, category: null, status: null, image: '/media/cards/person.svg', tags: [], group: 'person' };
    case 'document':
      return { kind: 'document', title: it.title, summary: `${it.type} · ${it.archive}`, category: null, status: null, image: '/media/cards/document.svg', tags: [], group: 'document' };
    case 'location':
      return { kind: 'location', title: it.name, summary: it.description, category: null, status: null, image: '/media/cards/location.svg', tags: [it.country], group: 'location' };
    default:
      throw new Error(type);
  }
}
const nodeId = (type, key) => `(SELECT id FROM board_nodes WHERE board_id = 1 AND entity_type = ${q(type)} AND entity_id = ${idOf(type, key)})`;
let cards = 0;
function addNode(type, key, x, y) {
  onWall.add(`${type}:${key}`);
  const n = nodeFor(type, key);
  emit(
    `INSERT INTO board_nodes (board_id, entity_type, entity_id, kind, title, summary, category_slug, evidence_status, image_path, tags_json, group_key) SELECT 1, ${q(type)}, ${idOf(type, key)}, ${q(n.kind)}, ${q(n.title)}, ${q(String(n.summary).slice(0, 1000))}, ${q(n.category)}, ${q(n.status)}, ${q(n.image)}, ${q(JSON.stringify(n.tags))}, ${q(n.group)} WHERE NOT EXISTS ${nodeId(type, key).replace('(SELECT id', '(SELECT 1')};`,
  );
  emit(`INSERT OR IGNORE INTO board_positions (board_id, node_id, x, y) VALUES (1, ${nodeId(type, key)}, ${x}, ${y});`);
  cards++;
}

const COLS = 4;
const DX = 1250;
const DY = 1000;
const firstRow = Math.ceil(seed.theories.length / COLS);
const rels = list('relationships');
list('theories').forEach((t, i) => {
  const col = i % COLS;
  const row = firstRow + Math.floor(i / COLS);
  const cx = col * DX - ((COLS - 1) * DX) / 2;
  const cy = row * DY - DY / 2;
  addNode('theory', t.key, cx, cy);
  const fresh = rels.filter(([ft, fk, tt, tk]) => ft === 'theory' && fk === t.key && tt !== 'theory' && !onWall.has(`${tt}:${tk}`));
  fresh.forEach(([, , tt, tk], j) => {
    const angle = (2 * Math.PI * j) / Math.max(fresh.length, 1) - Math.PI / 2;
    const radius = fresh.length > 8 ? 430 : 360;
    addNode(tt, tk, Math.round(cx + radius * 1.25 * Math.cos(angle)), Math.round(cy + radius * Math.sin(angle)));
  });
});

let threads = 0;
for (const r of rels) {
  const [ft, fk, tt, tk, kind, verification, label] = r;
  if (!onWall.has(`${ft}:${fk}`) || !onWall.has(`${tt}:${tk}`)) continue;
  emit(
    `INSERT OR IGNORE INTO board_edges (board_id, source_node_id, target_node_id, kind, verification, label, relationship_id) VALUES (1, ${nodeId(ft, fk)}, ${nodeId(tt, tk)}, ${q(kind)}, ${q(verification)}, ${q(label)}, ${relId(r)});`,
  );
  threads++;
}

writeFileSync(resolve(outFile), out.join('\n') + '\n');
console.log(`Wrote ${outFile}: ${out.length} statements, ${cards} wall cards, ${threads} threads.`);
