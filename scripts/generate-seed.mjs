#!/usr/bin/env node
// Generates migrations/d1/0002_seed.sql from data/seed.mjs.
// Usage: node scripts/generate-seed.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as seed from '../data/seed.mjs';
import { sqlLiteral as q } from '../shared/backup-core.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = [];
const emit = (s) => out.push(s);
const ids = {};
const idOf = (type, key) => {
  const id = ids[type]?.[key];
  if (!id) throw new Error(`Unknown ${type} key: ${key}`);
  return id;
};
const assign = (type, list) => {
  ids[type] = {};
  list.forEach((item, i) => (ids[type][item.key ?? item[0]] = i + 1));
};
const slugify = (s) =>
  s
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

emit('-- Initial archive content. Generated by scripts/generate-seed.mjs from data/seed.mjs – do not edit by hand.');
emit('-- Source URLs must be verified before deployment (see README, "Source verification").');

// Categories
assign('category', seed.categories);
seed.categories.forEach(([slug, name, desc], i) => {
  emit(`INSERT INTO categories (id, slug, name, description, sort_order) VALUES (${i + 1}, ${q(slug)}, ${q(name)}, ${q(desc)}, ${i});`);
});
const catId = (slug) => idOf('category', slug);

// Locations
assign('location', seed.locations);
seed.locations.forEach((l, i) => {
  emit(
    `INSERT INTO locations (id, slug, name, country_code, lat, lng, region_kind, description) VALUES (${i + 1}, ${q(l.key)}, ${q(l.name)}, ${q(l.country)}, ${l.lat}, ${l.lng}, ${q(l.kind)}, ${q(l.description)});`,
  );
});

// Organizations
assign('organization', seed.organizations);
seed.organizations.forEach((o, i) => {
  emit(
    `INSERT INTO organizations (id, slug, name, kind, description, founded, country, location_id) VALUES (${i + 1}, ${q(o.key)}, ${q(o.name)}, ${q(o.kind)}, ${q(o.description)}, ${q(o.founded)}, ${q(o.country)}, ${o.location ? idOf('location', o.location) : 'NULL'});`,
  );
});

// People
assign('person', seed.people);
seed.people.forEach((p, i) => {
  emit(
    `INSERT INTO people (id, slug, name, role, description, born, died) VALUES (${i + 1}, ${q(p.key)}, ${q(p.name)}, ${q(p.role)}, ${q(p.description)}, ${q(p.born)}, ${q(p.died)});`,
  );
});

// Sources
assign('source', seed.sources);
seed.sources.forEach((s, i) => {
  emit(
    `INSERT INTO sources (id, title, publisher, author, published_date, source_type, is_primary, url, last_checked, quality_note, notes) VALUES (${i + 1}, ${q(s.title)}, ${q(s.publisher)}, ${q(s.author)}, ${q(s.date)}, ${q(s.type)}, ${s.primary ? 1 : 0}, ${q(s.url)}, NULL, ${q(s.quality)}, ${q(s.url ? 'URL pending manual verification.' : 'Print/offline source; no URL.')});`,
  );
});

// Theories, tags, claims, counter-arguments, evidence
assign('theory', seed.theories);
const tagIds = new Map();
let claimId = 0;
let counterId = 0;
let evidenceId = 0;
const translations = [];
for (const [i, t] of seed.theories.entries()) {
  const id = i + 1;
  const body = {
    type: 'doc',
    content: [t.background, t.origin].filter(Boolean).map((p) => ({ type: 'paragraph', content: [{ type: 'text', text: p }] })),
  };
  emit(
    `INSERT INTO theories (id, slug, title, subtitle, summary, background, origin_story, body_json, category_id, evidence_status, image_path, image_credit, origin, is_published, created_at, updated_at) VALUES (${id}, ${q(t.slug)}, ${q(t.title)}, ${q(t.subtitle)}, ${q(t.summary)}, ${q(t.background)}, ${q(t.origin)}, ${q(JSON.stringify(body))}, ${catId(t.category)}, ${q(t.status)}, ${q(t.image)}, ${q('Original illustration, The Conspiracy Atlas (see LICENSES.md)')}, 'editorial', 1, '2026-10-30 00:00:00', '2026-10-30 00:00:0${i}');`,
  );
  for (const tag of t.tags) {
    const slug = slugify(tag);
    if (!tagIds.has(slug)) {
      tagIds.set(slug, tagIds.size + 1);
      emit(`INSERT INTO tags (id, slug, name) VALUES (${tagIds.get(slug)}, ${q(slug)}, ${q(tag)});`);
    }
    emit(`INSERT INTO theory_tags (theory_id, tag_id) VALUES (${id}, ${tagIds.get(slug)});`);
  }
  let counterIndex = 0;
  t.claims.forEach(([text, status, sourceKeys, counter, counterSources], ci) => {
    const cid = ++claimId;
    emit(`INSERT INTO claims (id, theory_id, text, evidence_status, position) VALUES (${cid}, ${id}, ${q(text)}, ${q(status)}, ${ci});`);
    for (const sk of sourceKeys) {
      // Origin publications of a claim are recorded as "context", never as proof.
      const relation = status === 'historically_documented' || status === 'supported_by_evidence' ? 'documents' : 'context';
      emit(`INSERT INTO evidence (id, source_id, theory_id, claim_id, relation) VALUES (${++evidenceId}, ${idOf('source', sk)}, ${id}, ${cid}, ${q(relation)});`);
    }
    if (counter) {
      const caid = ++counterId;
      emit(`INSERT INTO counter_arguments (id, theory_id, claim_id, text, position) VALUES (${caid}, ${id}, ${cid}, ${q(counter)}, ${counterIndex});`);
      for (const sk of counterSources ?? []) {
        emit(`INSERT INTO evidence (id, source_id, theory_id, counter_argument_id, relation) VALUES (${++evidenceId}, ${idOf('source', sk)}, ${id}, ${caid}, 'refutes');`);
      }
      if (t.de?.counters?.[counterIndex]) translations.push(['counter_argument', caid, 'text', t.de.counters[counterIndex]]);
      counterIndex++;
    }
    if (t.de?.claims?.[ci]) translations.push(['claim', cid, 'text', t.de.claims[ci]]);
  });
  for (const [sk, relation, note] of t.general ?? []) {
    emit(`INSERT INTO evidence (id, source_id, theory_id, relation, note) VALUES (${++evidenceId}, ${idOf('source', sk)}, ${id}, ${q(relation)}, ${q(note)});`);
  }
  if (t.de) {
    for (const f of ['title', 'subtitle', 'summary', 'background']) if (t.de[f]) translations.push(['theory', id, f, t.de[f]]);
  }
}

// Events
assign('event', seed.events);
seed.events.forEach((e, i) => {
  emit(
    `INSERT INTO events (id, slug, title, description, start_date, end_date, start_year, end_year, is_period, location_id, category_id, evidence_status) VALUES (${i + 1}, ${q(e.key)}, ${q(e.title)}, ${q(e.description)}, ${q(e.start)}, ${q(e.end ?? null)}, ${e.year}, ${e.endYear ?? 'NULL'}, ${e.period ? 1 : 0}, ${e.location ? idOf('location', e.location) : 'NULL'}, ${catId(e.category)}, ${q(e.status)});`,
  );
  if (e.de) {
    translations.push(['event', i + 1, 'title', e.de[0]]);
    translations.push(['event', i + 1, 'description', e.de[1]]);
  }
});

// Documents
assign('document', seed.documents);
seed.documents.forEach((d, i) => {
  const src = seed.sources.find((s) => s.key === d.source);
  emit(
    `INSERT INTO documents (id, slug, title, description, document_type, url, source_id, published_date, archive_name, license_note) VALUES (${i + 1}, ${q(d.key)}, ${q(d.title)}, ${q(src.quality)}, ${q(d.type)}, ${q(src.url)}, ${idOf('source', d.source)}, ${q(src.date)}, ${q(d.archive)}, ${q(d.license)});`,
  );
});

// Relationships
seed.relationships.forEach(([ft, fk, tt, tk, kind, verification, label], i) => {
  emit(
    `INSERT INTO relationships (id, from_type, from_id, to_type, to_id, kind, verification, label) VALUES (${i + 1}, ${q(ft)}, ${idOf(ft, fk)}, ${q(tt)}, ${idOf(tt, tk)}, ${q(kind)}, ${q(verification)}, ${q(label)});`,
  );
});

// Translations (German)
for (const [slug, [name, desc]] of Object.entries(seed.categoriesDe)) {
  translations.push(['category', catId(slug), 'name', name], ['category', catId(slug), 'description', desc]);
}
for (const [type, id, field, value] of translations) {
  emit(`INSERT INTO translations (entity_type, entity_id, locale, field, value) VALUES (${q(type)}, ${id}, 'de', ${q(field)}, ${q(value)});`);
}

// Main investigation wall ---------------------------------------------------------------------
emit(`INSERT INTO boards (id, slug, title, description, visibility) VALUES (1, 'main', 'The Investigation Wall', 'The public investigation wall of the archive.', 'public');`);

const nodes = []; // {type,key,kind,title,summary,category,status,image,tags,group,x,y}
const nodeIndex = new Map();
const addNode = (n) => {
  const k = `${n.type}:${n.key}`;
  if (nodeIndex.has(k)) return nodeIndex.get(k);
  n.id = nodes.length + 1;
  nodes.push(n);
  nodeIndex.set(k, n.id);
  return n.id;
};

const lookup = {
  theory: Object.fromEntries(seed.theories.map((t) => [t.key, t])),
  event: Object.fromEntries(seed.events.map((e) => [e.key, e])),
  organization: Object.fromEntries(seed.organizations.map((o) => [o.key, o])),
  person: Object.fromEntries(seed.people.map((p) => [p.key, p])),
  document: Object.fromEntries(seed.documents.map((d) => [d.key, d])),
  location: Object.fromEntries(seed.locations.map((l) => [l.key, l])),
};

function nodeFor(type, key) {
  const item = lookup[type][key];
  switch (type) {
    case 'theory':
      return { type, key, kind: 'theory', title: item.title, summary: item.summary, category: item.category, status: item.status, image: item.image, tags: item.tags, group: item.category };
    case 'event':
      return { type, key, kind: 'event', title: item.title, summary: `${item.start}${item.end ? ` – ${item.end}` : ''}: ${item.description}`, category: item.category, status: item.status, image: '/assets/cards/event.svg', tags: [String(item.year)], group: 'event' };
    case 'organization':
      return { type, key, kind: ['agency', 'commission', 'institution'].includes(item.kind) ? 'institution' : 'organization', title: item.name, summary: item.description, category: null, status: null, image: '/assets/cards/organization.svg', tags: [item.country], group: 'organization' };
    case 'person':
      return { type, key, kind: 'person', title: item.name, summary: `${item.role}. ${item.description}`, category: null, status: null, image: '/assets/cards/person.svg', tags: [], group: 'person' };
    case 'document':
      return { type, key, kind: 'document', title: item.title, summary: `${item.type} · ${item.archive}`, category: null, status: null, image: '/assets/cards/document.svg', tags: [], group: 'document' };
    case 'location':
      return { type, key, kind: 'location', title: item.name, summary: item.description, category: null, status: null, image: '/assets/cards/location.svg', tags: [item.country], group: 'location' };
    default:
      throw new Error(type);
  }
}

// Theories on a 4 x 2 grid; their direct connections are arranged on a ring around them.
const COLS = 4;
const DX = 1250;
const DY = 1000;
seed.theories.forEach((t, i) => {
  const col = i % COLS;
  const row = Math.floor(i / COLS);
  const cx = col * DX - ((COLS - 1) * DX) / 2;
  const cy = row * DY - DY / 2;
  const n = nodeFor('theory', t.key);
  n.x = cx;
  n.y = cy;
  addNode(n);
  const linked = seed.relationships.filter(([ft, fk, tt]) => ft === 'theory' && fk === t.key && tt !== 'theory' && lookup[tt]);
  const fresh = linked.filter(([, , tt, tk]) => !nodeIndex.has(`${tt}:${tk}`));
  fresh.forEach(([, , tt, tk], j) => {
    const angle = (2 * Math.PI * j) / Math.max(fresh.length, 1) - Math.PI / 2;
    const radius = fresh.length > 8 ? 430 : 360;
    const m = nodeFor(tt, tk);
    m.x = Math.round(cx + radius * 1.25 * Math.cos(angle));
    m.y = Math.round(cy + radius * Math.sin(angle));
    addNode(m);
  });
});

for (const n of nodes) {
  emit(
    `INSERT INTO board_nodes (id, board_id, entity_type, entity_id, kind, title, summary, category_slug, evidence_status, image_path, tags_json, group_key) VALUES (${n.id}, 1, ${q(n.type)}, ${idOf(n.type, n.key)}, ${q(n.kind)}, ${q(n.title)}, ${q(String(n.summary).slice(0, 1000))}, ${q(n.category)}, ${q(n.status)}, ${q(n.image)}, ${q(JSON.stringify(n.tags))}, ${q(n.group)});`,
  );
  emit(`INSERT INTO board_positions (board_id, node_id, x, y) VALUES (1, ${n.id}, ${n.x}, ${n.y});`);
}

let edgeId = 0;
seed.relationships.forEach(([ft, fk, tt, tk, kind, verification, label], i) => {
  const s = nodeIndex.get(`${ft}:${fk}`);
  const t = nodeIndex.get(`${tt}:${tk}`);
  if (!s || !t) return;
  emit(
    `INSERT INTO board_edges (id, board_id, source_node_id, target_node_id, kind, verification, label, relationship_id) VALUES (${++edgeId}, 1, ${s}, ${t}, ${q(kind)}, ${q(verification)}, ${q(label)}, ${i + 1});`,
  );
});

emit(`INSERT INTO settings (key, value) VALUES ('seed_version', '1');`);

const file = join(root, 'migrations', 'd1', '0002_seed.sql');
writeFileSync(file, out.join('\n') + '\n');
console.log(`Wrote ${file}: ${out.length} statements, ${nodes.length} wall cards, ${edgeId} threads.`);
