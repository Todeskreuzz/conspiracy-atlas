#!/usr/bin/env node
// Spanish translations for the editorial archive, as an additive migration.
// Does not rewrite the English rows or the German migration. Sources stay in English.
// Usage: node scripts/generate-spanish.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as seed from '../data/seed.mjs';
import * as batch from '../data/cases-2.mjs';
import * as es from '../data/spanish.mjs';
import { sqlLiteral as q } from '../shared/backup-core.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = [];
const emit = (s) => out.push(s);

const theories = [...seed.theories, ...(batch.theories ?? [])];
const events = [...seed.events, ...(batch.events ?? [])];

function translation(type, idSql, field, value) {
  emit(
    `INSERT OR REPLACE INTO translations (entity_type, entity_id, locale, field, value) VALUES (${q(type)}, ${idSql}, 'es', ${q(field)}, ${q(value)});`,
  );
}

emit('-- Spanish texts for the editorial case files, events and categories.');
emit('-- Generated by scripts/generate-spanish.mjs from data/spanish.mjs – do not edit by hand.');
emit('-- Sources, people and organisations stay in English. Apply with the other D1 migrations.');

for (const [slug, [name, desc]] of Object.entries(es.categories)) {
  if (!seed.categories.some(([s]) => s === slug)) throw new Error(`Unknown category ${slug}`);
  const id = `(SELECT id FROM categories WHERE slug = ${q(slug)})`;
  translation('category', id, 'name', name);
  translation('category', id, 'description', desc);
}

for (const t of theories) {
  const text = es.theories[t.slug];
  if (!text) throw new Error(`Missing Spanish theory ${t.slug}`);
  const counters = t.claims.filter((c) => c[3]).length;
  if (text.claims.length !== t.claims.length) throw new Error(`${t.slug}: ${text.claims.length} Spanish claims, ${t.claims.length} English`);
  if ((text.counters?.length ?? 0) !== counters) throw new Error(`${t.slug}: counter count`);
  for (const field of ['title', 'subtitle', 'summary', 'background']) {
    if (!text[field]) throw new Error(`${t.slug}: missing ${field}`);
  }
  const id = `(SELECT id FROM theories WHERE slug = ${q(t.slug)})`;
  for (const field of ['title', 'subtitle', 'summary', 'background']) translation('theory', id, field, text[field]);
  let counterIndex = 0;
  t.claims.forEach((claim, position) => {
    const claimId = `(SELECT id FROM claims WHERE theory_id = ${id} AND position = ${position})`;
    translation('claim', claimId, 'text', text.claims[position]);
    if (claim[3]) {
      translation('counter_argument', `(SELECT id FROM counter_arguments WHERE claim_id = ${claimId})`, 'text', text.counters[counterIndex]);
      counterIndex++;
    }
  });
}

for (const e of events) {
  const pair = es.events[e.key];
  if (!pair || pair.length !== 2) throw new Error(`Missing Spanish event ${e.key}`);
  const id = `(SELECT id FROM events WHERE slug = ${q(e.key)})`;
  translation('event', id, 'title', pair[0]);
  translation('event', id, 'description', pair[1]);
}

const extraTheories = Object.keys(es.theories).filter((slug) => !theories.some((t) => t.slug === slug));
const extraEvents = Object.keys(es.events).filter((key) => !events.some((e) => e.key === key));
if (extraTheories.length || extraEvents.length) throw new Error(`Unknown Spanish keys: ${extraTheories.concat(extraEvents).join(', ')}`);

const file = join(root, 'migrations/d1/0015_spanish.sql');
writeFileSync(file, out.join('\n') + '\n');
console.log(`wrote ${file} (${out.length - 3} translations)`);
